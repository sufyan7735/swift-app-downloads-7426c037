const applyPhrases = (text: string, phrases: [string, string][]) => {
  let out = text;
  for (const [ar, en] of [...phrases].sort((a, b) => b[0].length - a[0].length)) out = out.split(ar).join(en);
  // واو العطف المنفردة فقط (لا تلمس الكلمات التي تبدأ بواو)
  out = out.replace(/(^|\s)و(\s)/g, "$1and$2").replace(/\sو(?=[A-Za-z0-9])/g, " and ");
  return out.replace(/\s{2,}/g, " ").trim();
};

/** يترجم عنوان مجموعة مواصفات. */
export const translateGroupTitle = (t: string) => GROUP_TITLES_EN[t] ?? applyPhrases(t, VALUE_PHRASES_EN);

/** يترجم مسمّى صف مواصفات. */
export const translateSpecLabel = (l: string) => SPEC_LABELS_EN[l] ?? applyPhrases(l, VALUE_PHRASES_EN);

/** يترجم قيمة مواصفة (معظم القيم أرقام ووحدات لاتينية). */
export const translateSpecValue = (v: string) =>
  /[\u0600-\u06FF]/.test(v) ? applyPhrases(v, VALUE_PHRASES_EN) : v;

/** يترجم اسم المنتج التجاري. */
export const translateProductName = (n: string) => applyPhrases(n.replace(/\u200f/g, " "), NAME_PHRASES_EN);
