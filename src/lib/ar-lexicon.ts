const ONES = ["صفر", "واحد", "اثنان", "ثلاثة", "أربعة", "خمسة", "ستة", "سبعة", "ثمانية", "تسعة", "عشرة",
  "أحد عشر", "اثنا عشر", "ثلاثة عشر", "أربعة عشر", "خمسة عشر", "ستة عشر", "سبعة عشر", "ثمانية عشر", "تسعة عشر"];
const TENS = ["", "", "عشرون", "ثلاثون", "أربعون", "خمسون", "ستون", "سبعون", "ثمانون", "تسعون"];
const HUNDREDS = ["", "مئة", "مئتان", "ثلاثمئة", "أربعمئة", "خمسمئة", "ستمئة", "سبعمئة", "ثمانمئة", "تسعمئة"];

function below1000(n: number): string {
  const h = Math.floor(n / 100), r = n % 100, parts: string[] = [];
  if (h) parts.push(HUNDREDS[h]!);
  if (r) {
    if (r < 20) parts.push(ONES[r]!);
    else { const o = r % 10; parts.push(o ? `${ONES[o]} و${TENS[Math.floor(r / 10)]}` : TENS[Math.floor(r / 10)]!); }
  }
  return parts.join(" و");
}

export function numberToArabicWords(n: number): string {
  if (!Number.isFinite(n)) return String(n);
  if (n < 0) return "سالب " + numberToArabicWords(-n);
  if (!Number.isInteger(n)) {
    const [i, d] = String(n).split(".");
    const dec = d!.length <= 2 && !d!.startsWith("0") ? numberToArabicWords(Number(d)) : d!.split("").map((c) => ONES[Number(c)]).join(" ");
    return `${numberToArabicWords(Number(i))} فاصلة ${dec}`;
  }
  if (n === 0) return ONES[0]!;
  const groups: [number, string, string, string][] = [
    [1e9, "مليار", "ملياران", "مليارات"],
    [1e6, "مليون", "مليونان", "ملايين"],
    [1e3, "ألف", "ألفان", "آلاف"],
  ];
  const parts: string[] = [];
  let rest = n;
  for (const [v, one, two, many] of groups) {
    const q = Math.floor(rest / v);
    rest %= v;
    if (!q) continue;
    if (q === 1) parts.push(one);
    else if (q === 2) parts.push(two);
    else if (q <= 10) parts.push(`${below1000(q)} ${many}`);
    else parts.push(`${below1000(q)} ${one}`);
  }
  if (rest) parts.push(below1000(rest));
  return parts.join(" و");
}

/** يهيّئ النص العربي للنطق: مصطلحات، أرقام، رموز. */
export function prepareArabicSpeech(text: string): string {
  let t = text
    .replace(/[\u0660-\u0669]/g, (d) => String(d.charCodeAt(0) - 0x0660))
    .replace(/(\d),(?=\d{3}(?!\d))/g, "$1")
    .replace(/(\d),(?=\d{3}(?!\d))/g, "$1")
    .replace(/(\d),(?=\d{3}(?!\d))/g, "$1")
    .replace(/%/g, " بالمئة")
    // أكواد موديلات المصنع بين قوسين (لاتينية/أرقام فقط) لا تُنطق
    .replace(/[（(][^()（）\u0621-\u064A]*(?:[（(][^()（）\u0621-\u064A]*[)）])?[^()（）\u0621-\u064A]*[)）]/g, " ")
    // رقم العرض: يُنطق حرفاً حرفاً ورقماً رقماً حتى لا تسقط الأصفار
    .replace(/\bACTES\s*-\s*([A-Za-z]+)\s*(\d+)/g, (_m, letters: string, digits: string) => {
      const L: Record<string, string> = { A: "إيه", B: "بي", C: "سي", D: "دي", E: "إي", F: "إف", G: "جي", H: "إتش", I: "آي", J: "جيه", K: "كيه", L: "إل", M: "إم", N: "إن", O: "أو", P: "بي", Q: "كيو", R: "آر", S: "إس", T: "تي", U: "يو", V: "في", W: "دبليو", X: "إكس", Y: "واي", Z: "زد" };
      const spelled = letters.toUpperCase().split("").map((c) => L[c] || c).join(" ");
      const nums = digits.split("").map((c) => ONES[Number(c)]).join(" ");
      return `أَكْتِسْ ${spelled} ${nums} `;
    })
    .replace(/\bACTES\s*-\s*/gi, "ACTES، ")
    .replace(/(\d)(?=[A-Za-z\u0621-\u064A])/g, "$1 ")
    .replace(/([A-Za-z])(?=\d)/g, "$1 ")
    .replace(/(\d)\s*A\b/g, "$1 أمبير")
    .replace(/(\d)\s*[Vv](?![A-Za-z])/g, "$1 فولت")
    .replace(/(\d)\s*Hz\b/gi, "$1 هرتز")
    .replace(/(سوليس|سوليز)([^A-Za-z]{0,20})\bSOLIS\b/gi, "$1$2")
    .replace(/\bSOLIS\b/gi, "سوليس")
    .replace(/\bOn\s*Grid\b/gi, "مُرْتَبِطٌ بِالشَّبَكَة")
    .replace(/\bOff\s*Grid\b/gi, "مُنْفَصِلٌ عَنِ الشَّبَكَة")
    .replace(/\bHybrid\b/gi, "هَجِين")
    .replace(/\bResidential\b/gi, "سَكَنِي")
    .replace(/\bCommercial\b/gi, "تِجَارِي")
    .replace(/\bAgricultural\b/gi, "زِرَاعِي")
    .replace(/\bIndustrial\b/gi, "صِنَاعِي")
    .replace(/\b(?:Coming\s*soon|Back\s*to\s*Start|Back\s*one\s*step|Res|Com|Ind|Via|Study)\b/gi, " ")
    .replace(/(\d)\s*[×xX]\s*(\d)/g, "$1 في $2")
    .replace(/(?<![\u0621-\u064A\u064B-\u0652])ر\.\s*[يس]\.?(?![\u0621-\u064A])|(?<![\u0621-\u064A\u064B-\u0652])ر[يس](?![\u0621-\u064A\u064B-\u0652])/g, " ريال")
    .replace(/[\u{1F300}-\u{1FAFF}\u2600-\u27BF]/gu, " ");
  // «كيلو» وحدها: بعد البطارية/الليثيوم = كيلوواط ساعة، ومع المنظومات والإنفرترات = كيلوواط،
  // وتبقى «كيلو» كما هي مع الأوزان (طفاية/جرام/كجم).
  t = t
    .replace(/((?:بطارية|بطاريات|ليثيوم|كبينة|راك|بايلونتك|هيثيوم|فيدوس)[^—\-\n]{0,30}?\d+(?:\.\d+)?)\s*كيلو(?!\s*(?:وات|واط|فولت|ساعة|جرام|غرام|جم))/g, "$1 كيلوواط ساعة")
    .replace(/((?:ان|إن|أن)فرتر[^—\-\n]{0,30}?\d+(?:\.\d+)?)\s*كيلو(?!\s*(?:وات|واط|فولت|ساعة|جرام|غرام|جم))/g, "$1 كيلوواط")
    .replace(/((?:منظومة|منظومات|نظام|ليو\s*باور|سولي[سز]|دايا|سنتك|هجين|هايبرد)[^—\-\n]{0,30}?\d+(?:\.\d+)?)\s*كيلو(?!\s*(?:وات|واط|فولت|ساعة|جرام|غرام|جم))/g, "$1 كيلوواط");
  // ما تبقى من «كيلو» عارية يُقرأ كيلوواط، إلا في سياق الأوزان (طفايات الحريق والمكيالات)
  if (!/حريق|طفاي|مطفأ|وزن|كجم|كغم|حاملها/.test(t)) {
    t = t.replace(/(\d+(?:\.\d+)?)\s*كيلو(?![\u0621-\u064A])(?!\s*(?:وات|واط|فولت|ساعة|جرام|غرام|جم))/g, "$1 كيلوواط");
  }
  t = t.replace(/\d+(?:\.\d+)?/g, (m) => numberToArabicWords(Number(m)));
  for (const [re, rep] of TERMS) t = t.replace(re, rep);
  return applyWaqf(t.replace(/\s+/g, " ").trim());
}

/**
 * الوقف بالسكون: آخر حرف قبل علامة الترقيم أو نهاية العبارة يُسكَّن،
 * حتى لا يُنطق مفتوحاً («لمشروعكا») بل ساكناً («لمشروعكْ»).
 * حروف المد والتاء المربوطة والهمزة تُترك بلا سكون مرسوم لأن وقفها طبيعي.
 */
export function applyWaqf(text: string): string {
  const skip = new Set(["ا", "ى", "و", "ي", "ة", "ء", "آ", "أ", "إ", "ؤ", "ئ"]);
  return text.replace(
    /([\u0621-\u064A])([\u064B-\u0652\u0670]*)(?=\s*(?:[.،,!؟?;:؛]|$))/g,
    (match, letter: string, marks: string) => {
      if (skip.has(letter)) return match;
      // تنوين النصب المرسوم على الحرف قبل الألف يبقى كما هو
      if (/[\u064B\u064C\u064D]/.test(marks)) return match;
      const shadda = marks.includes("\u0651") ? "\u0651" : "";
      return `${letter}${shadda}\u0652`;
    },
  );
}

