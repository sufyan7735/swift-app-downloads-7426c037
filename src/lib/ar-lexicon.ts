export function diacritizeNumberWords(text: string): string {
  let t = text;
  for (const [plain, marked] of NUM_WORDS) {
    t = t.replace(
      new RegExp(`(?<![\\u0621-\\u064A\\u064B-\\u0652])(و?)${plain}(?![\\u0621-\\u064A\\u064B-\\u0652])`, "g"),
      (_m, waw: string) => `${waw ? "وَ" : ""}${marked}`,
    );
  }
  return t;
}

/** نسبة الحروف المُشكَّلة؛ النصوص المكتوبة يدوياً بالتشكيل لا تحتاج مُشكِّلاً آلياً. */
export function isDiacritized(text: string) {
  const letters = (text.match(/[\u0621-\u064A]/g) || []).length;
  const marks = (text.match(/[\u064B-\u0652]/g) || []).length;
  return letters > 0 && marks / letters > 0.55;
}
